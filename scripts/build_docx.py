"""Convert docs/proposal.md into a formatted Word document (docs/Proposal_AI_Air_Doctor.docx).

Supports: headings, paragraphs, bullets, numbered lists, tables, blockquotes,
code blocks, **bold**, `code`. Mermaid blocks are replaced by PNG diagrams
generated by diagrams.py (in order: architecture, flowchart).
"""
import os
import re
from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

BASE = os.path.join(os.path.dirname(__file__), "..")
MD = os.path.join(BASE, "docs", "proposal.md")
IMG = os.path.join(BASE, "docs", "img")
OUT = os.path.join(BASE, "docs", "Proposal_AI_Air_Doctor.docx")
FONT = "Microsoft JhengHei"
MERMAID_IMAGES = ["architecture.png", "flowchart.png"]


def set_font(run, size=None, bold=None, color=None, mono=False, italic=None):
    name = "Consolas" if mono else FONT
    run.font.name = name
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:eastAsia"), FONT)
    if size:
        run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if italic is not None:
        run.italic = italic
    if color:
        run.font.color.rgb = RGBColor.from_string(color)


def add_inline(par, text, size=11, color=None, italic=None):
    for part in re.split(r"(\*\*[^*]+\*\*|`[^`]+`)", text):
        if not part:
            continue
        if part.startswith("**") and part.endswith("**"):
            set_font(par.add_run(part[2:-2]), size, True, color, italic=italic)
        elif part.startswith("`") and part.endswith("`"):
            set_font(par.add_run(part[1:-1]), size - 1, False, "C7254E", mono=True)
        else:
            set_font(par.add_run(part), size, None, color, italic=italic)


def shade(cell, hex_color):
    tcpr = cell._element.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcpr.append(shd)


def add_table(doc, rows):
    header, body = rows[0], rows[1:]
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    small = 8.5 if len(header) >= 6 else 10
    for i, h in enumerate(header):
        c = t.rows[0].cells[i]
        c.text = ""
        add_inline(c.paragraphs[0], h, small, "FFFFFF")
        c.paragraphs[0].runs and setattr(c.paragraphs[0].runs[0], "bold", True)
        shade(c, "0E7490")
    for r_i, r in enumerate(body):
        cells = t.add_row().cells
        for i in range(len(header)):
            cells[i].text = ""
            add_inline(cells[i].paragraphs[0], r[i] if i < len(r) else "", small)
            if r_i % 2:
                shade(cells[i], "ECFEFF")
    doc.add_paragraph()


def parse_row(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def build():
    doc = Document()
    sec = doc.sections[0]
    sec.left_margin = sec.right_margin = Cm(2.2)
    sec.top_margin = sec.bottom_margin = Cm(2.2)
    normal = doc.styles["Normal"]
    normal.font.name = FONT
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    normal.font.size = Pt(11)
    normal.paragraph_format.line_spacing = 1.3
    normal.paragraph_format.space_after = Pt(4)

    lines = open(MD, encoding="utf-8").read().splitlines()
    i, mermaid_idx, first_h1 = 0, 0, True
    while i < len(lines):
        line = lines[i]
        s = line.strip()

        if s.startswith("```"):
            lang = s[3:].strip()
            block = []
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                block.append(lines[i])
                i += 1
            i += 1
            if lang == "mermaid":
                if mermaid_idx < len(MERMAID_IMAGES):
                    p = doc.add_paragraph()
                    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                    w = Cm(15.5) if mermaid_idx == 0 else Cm(11)
                    p.add_run().add_picture(os.path.join(IMG, MERMAID_IMAGES[mermaid_idx]), width=w)
                    cap = doc.add_paragraph()
                    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
                    add_inline(cap, ["圖 1:系統架構圖", "圖 2:系統流程圖"][mermaid_idx], 9.5, "475569")
                mermaid_idx += 1
            else:
                t = doc.add_table(rows=1, cols=1)
                t.style = "Table Grid"
                c = t.rows[0].cells[0]
                shade(c, "F1F5F9")
                c.text = ""
                p = c.paragraphs[0]
                for j, b in enumerate(block):
                    r = p.add_run(b)
                    set_font(r, 9, mono=True)
                    if j < len(block) - 1:
                        r.add_break()
                doc.add_paragraph()
            continue

        if s.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                r = parse_row(lines[i])
                if not all(re.fullmatch(r":?-+:?", c) for c in r):
                    rows.append(r)
                i += 1
            add_table(doc, rows)
            continue

        if s in ("", "---"):
            i += 1
            continue

        if s.startswith("# "):
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_before = Pt(60 if first_h1 else 12)
            set_font(p.add_run(s[2:]), 20, True, "0E7490")
            first_h1 = False
        elif s.startswith("## "):
            p = doc.add_heading(level=1)
            set_font(p.add_run(s[3:]), 16, True, "0E7490")
        elif s.startswith("### "):
            p = doc.add_heading(level=2)
            set_font(p.add_run(s[4:]), 13, True, "155E75")
        elif s.startswith("> "):
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Cm(0.6)
            add_inline(p, s[2:], 10, "64748B", italic=True)
        elif re.match(r"^[-*] ", s):
            p = doc.add_paragraph(style="List Bullet")
            add_inline(p, s[2:])
        elif re.match(r"^\d+\. ", s):
            p = doc.add_paragraph(style="List Number")
            add_inline(p, re.sub(r"^\d+\. ", "", s))
        else:
            p = doc.add_paragraph()
            if s.startswith("**Proposal") or s.startswith("AI Air Doctor: A Domain"):
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            if line.startswith("組員") or line.startswith("課程"):
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            add_inline(p, s.rstrip("\\").strip())
            # page break after cover info
            if line.startswith("課程"):
                doc.add_page_break()
        i += 1

    doc.save(OUT)
    print("saved", os.path.abspath(OUT))


if __name__ == "__main__":
    build()
